#!/usr/bin/env python3
"""Regenerates port/source/nodata_font.h, the type of the "game data not found" screen (nodata.c).
That screen comes up when the pack (and with it the PC font) is missing, so it carries its own:
the website's three faces (site/fonts, SIL Open Font License 1.1), rasterized here for ASCII at the
sizes the screen uses, as 4-bit coverage with advances and kerning pairs.

  pip install Pillow && python3 tools/make_nodata_font.py
"""
import os

from PIL import Image, ImageDraw, ImageFont

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..')
FONTS = os.path.join(ROOT, 'site', 'fonts')
OUT = os.path.join(ROOT, 'port', 'source', 'nodata_font.h')

# (enum name, file, pixel size, what it is for); the order is the ND_* order in nodata.c
STYLES = [
    ('ND_LABEL', 'vt323-400-latin.woff2', 15, 'labels, letterspaced capitals'),   # VT323 is on its grid at 5 px steps
    ('ND_MONO', 'vt323-400-latin.woff2', 20, 'paths, addresses, step numbers'),
    ('ND_TITLE', 'libre-caslon-display-400-latin.woff2', 32, 'the heading, capitals'),
    ('ND_BODY', 'crimson-pro-latin.woff2', 16, 'text'),
    ('ND_ITALIC', 'crimson-pro-italic-latin.woff2', 17, 'the lede under the heading'),
]
FIRST, LAST = 32, 126
SUB = 8   # advances and kerning in 1/8 pixel


def glyph(font, ch):
    l, t, r, b = font.getbbox(ch, anchor='ls')
    if r <= l or b <= t:
        return 0, 0, 0, 0, b''
    im = Image.new('L', (r - l, b - t), 0)
    ImageDraw.Draw(im).text((-l, -t), ch, font=font, fill=255, anchor='ls')
    px = im.tobytes()
    nib = [min(15, (v + 8) // 17) for v in px]
    if len(nib) & 1:
        nib.append(0)
    data = bytes(nib[i] | nib[i + 1] << 4 for i in range(0, len(nib), 2))
    return r - l, b - t, l, t, data


def main():
    bits = bytearray()
    out = []
    for name, file, size, what in STYLES:
        font = ImageFont.truetype(os.path.join(FONTS, file), size)
        ascent, descent = font.getmetrics()
        glyphs = []
        for c in range(FIRST, LAST + 1):
            w, h, x, y, data = glyph(font, chr(c))
            adv = round(font.getlength(chr(c)) * SUB)
            glyphs.append((len(bits), w, h, x, y, adv))
            bits += data
        kern = []
        # pairs of a quarter pixel or more; the heading is set in capitals only
        chars = [chr(c) for c in range(FIRST + 1, LAST + 1) if name != 'ND_TITLE' or not chr(c).islower()]
        # kerning only: with ligatures on, "fi" would measure as its ligature and pull the i under the f
        nolig = ['-liga', '-clig', '-dlig', '-calt']
        single = {c: font.getlength(c, features=nolig) for c in chars}
        for a in chars:
            for b in chars:
                k = font.getlength(a + b, features=nolig) - single[a] - single[b]
                k8 = round(k * SUB)
                if abs(k8) >= SUB // 4:
                    kern.append((ord(a), ord(b), k8))
        out.append((name, file, size, what, ascent, descent, glyphs, kern))

    with open(OUT, 'w') as f:
        f.write('// The type of nodata.c, generated by tools/make_nodata_font.py from the website\'s fonts\n')
        f.write('// (site/fonts: Libre Caslon Display, Crimson Pro and VT323, SIL Open Font License 1.1, see\n')
        f.write('// site/fonts/OFL-*.txt). ASCII %d..%d per style; coverage 4 bits a pixel, low nibble first.\n' % (FIRST, LAST))
        f.write('#pragma once\n\n')
        f.write('#define ND_FIRST %d\n#define ND_LAST %d\n#define ND_SUB %d   // advances and kerning in 1/%d pixel\n\n'
                % (FIRST, LAST, SUB, SUB))
        f.write('enum {\n')
        for name, file, size, what, *_ in out:
            f.write('\t%s,%s// %s %d px: %s\n' % (name, ' ' * (10 - len(name)), file.split('-latin')[0], size, what))
        f.write('\tND_STYLES\n};\n\n')
        f.write('typedef struct {\n\tunsigned int off;          // into nd_bits\n'
                '\tunsigned char w, h;        // the coverage box\n'
                '\tsigned char x, y;          // its top left from the pen on the baseline\n'
                '\tunsigned short adv;        // in 1/ND_SUB pixel\n} NdGlyph;\n\n')
        f.write('typedef struct { unsigned char a, b; signed char k; } NdKern;   // k in 1/ND_SUB pixel\n\n')
        f.write('typedef struct {\n\tconst NdGlyph* glyph;      // ND_FIRST..ND_LAST\n\tconst NdKern* kern;\n'
                '\tint nkern;\n\tint ascent, descent;\n} NdFont;\n\n')
        for name, file, size, what, ascent, descent, glyphs, kern in out:
            low = name.lower()
            f.write('static const NdGlyph %s_glyph[] = {\n' % low)
            for i, (off, w, h, x, y, adv) in enumerate(glyphs):
                c = chr(FIRST + i)
                f.write('\t{%d, %d, %d, %d, %d, %d},   // %s\n' % (off, w, h, x, y, adv, repr(c)))
            f.write('};\n')
            f.write('static const NdKern %s_kern[] = {\n' % low)
            for a, b, k in kern:
                f.write('\t{%d, %d, %d},\n' % (a, b, k))
            if not kern:
                f.write('\t{0, 0, 0},\n')
            f.write('};\n\n')
        f.write('static const NdFont nd_font[ND_STYLES] = {\n')
        for name, file, size, what, ascent, descent, glyphs, kern in out:
            low = name.lower()
            f.write('\t{%s_glyph, %s_kern, %d, %d, %d},\n' % (low, low, len(kern), ascent, descent))
        f.write('};\n\n')
        f.write('static const unsigned char nd_bits[%d] = {\n' % len(bits))
        for i in range(0, len(bits), 24):
            f.write('\t' + ','.join('%d' % v for v in bits[i:i + 24]) + ',\n')
        f.write('};\n')
    print('wrote', os.path.relpath(OUT), '(%d bytes of coverage, %s kerning pairs)'
          % (len(bits), '/'.join(str(len(o[7])) for o in out)))


if __name__ == '__main__':
    main()
