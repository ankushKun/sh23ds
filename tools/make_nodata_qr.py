#!/usr/bin/env python3
"""Regenerates port/source/nodata_qr.h, the QR code on the "game data not found" screen (nodata.c).
It points at the website's install guide, so it only changes if that address does.

  pip install segno==1.6.1 && python3 tools/make_nodata_qr.py
"""
import os

import segno

URL = 'https://ankush.one/sh23ds/install.html'
OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'port', 'source', 'nodata_qr.h')

qr = segno.make(URL, error='m', boost_error=False)
rows = [row for row in qr.matrix]
n = len(rows)
assert n <= 32, 'one u32 per row'
with open(OUT, 'w') as f:
    f.write('// The QR code of %s, for nodata.c. Generated by tools/make_nodata_qr.py.\n' % URL)
    f.write('#pragma once\n\n')
    f.write('#define NODATA_QR_URL "%s"\n' % URL)
    f.write('#define NODATA_QR_SIZE %d   // modules per side, without the quiet zone\n\n' % n)
    f.write('// One row per entry, bit x (from the least significant) set for a dark module.\n')
    f.write('static const unsigned int nodata_qr[NODATA_QR_SIZE] = {\n')
    for row in rows:
        bits = sum(1 << x for x, v in enumerate(row) if v)
        f.write('\t0x%08x,\n' % bits)
    f.write('};\n')
print('wrote', os.path.relpath(OUT), '(%d x %d)' % (n, n))
