def cell_of(x, z):
    return int(x * 5e-5 + 16) * 32 + int(z * 5e-5 + 16)


def room_id(glb, x, z):
    t = ROOM_TABLE.get(glb)
    if t is None:
        return 0
    exact, even, default = t
    c = cell_of(x, z)
    if c in exact:
        return exact[c]
    return even.get((c - (c & 0x20)) - (c & 1), default)
